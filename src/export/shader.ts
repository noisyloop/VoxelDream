// Export the world as a self-contained GLSL fragment shader that runs
// unmodified as a Shadertoy "Image" shader.
//
// Shadertoy offers no custom texture upload, and drivers spill large const
// arrays into the uniform block (practical budget ~2-8 KB — see
// RESEARCH.md §2.5). So instead of baking 64³ of data, we bake:
//
//   1. a GLSL twin of the deterministic room generator (roomVoxel/pcg from
//      src/dreams/room.ts and src/core/hash.ts — same bits, same room), and
//   2. a sorted `const uint` array of everything the player changed —
//      one uint per edit: 18-bit position | 8-bit material — looked up by
//      binary search inside the ray marcher.
//
// The data cost scales with what the player did, not with world size.
// If you change roomVoxel() in TypeScript, change its twin below in the
// same commit; the golden test pins both.

import { MAT, type PaletteEntry } from "../core/palette";
import { roomVoxel, ROOM_SEED, ROOM_SIZE } from "../dreams/room";
import type { World } from "../core/world";

export interface ShaderExportResult {
  glsl: string;
  warnings: string[];
  editCount: number;
  lightCount: number;
}

/** Edits beyond this likely exceed Shadertoy's reliable const-data budget. */
export const MAX_SAFE_EDITS = 1500;
/** Lights beyond this still glow, but stop casting shadows in the export. */
export const MAX_EXPORT_LIGHTS = 16;

export function exportShader(
  world: World,
  palette: PaletteEntry[],
  seed = ROOM_SEED
): ShaderExportResult {
  const warnings: string[] = [];

  // Diff the world against the pristine generated room, and collect lights
  // and the set of materials actually present.
  const edits: number[] = [];
  const lights: { x: number; y: number; z: number; mat: number }[] = [];
  const usedMats = new Set<number>();
  for (let z = 0; z < ROOM_SIZE; z++) {
    for (let y = 0; y < ROOM_SIZE; y++) {
      for (let x = 0; x < ROOM_SIZE; x++) {
        const actual = world.get(x, y, z);
        const base = roomVoxel(x, y, z, seed);
        if (actual !== base) {
          edits.push((x | (y << 6) | (z << 12) | (actual << 18)) >>> 0);
        }
        if (actual !== 0) {
          usedMats.add(actual);
          if ((palette[actual]?.emissive ?? 0) > 0) lights.push({ x, y, z, mat: actual });
        }
      }
    }
  }
  // The generator's own materials must exist even if currently erased.
  for (const m of [MAT.WALL, MAT.FLOOR_A, MAT.FLOOR_B, MAT.CEILING, MAT.PILLAR, MAT.TRIM, MAT.RUBBLE]) {
    usedMats.add(m);
  }
  edits.sort((a, b) => (a & 0x3ffff) - (b & 0x3ffff));

  if (edits.length > MAX_SAFE_EDITS) {
    warnings.push(
      `${edits.length} edits exceed the ~${MAX_SAFE_EDITS} that reliably compile on Shadertoy ` +
        `(const arrays spill into the uniform block). The file was still written — it may compile ` +
        `slowly or fail on some drivers.`
    );
  }
  if (lights.length > MAX_EXPORT_LIGHTS) {
    warnings.push(
      `${lights.length} lights in the scene; only the first ${MAX_EXPORT_LIGHTS} cast shadows in ` +
        `the exported shader (they all still glow).`
    );
  }
  const shadowLights = lights.slice(0, MAX_EXPORT_LIGHTS);

  // Brick-level occupancy of the *final* world (8³ bricks → 512 bits = 16 uints),
  // so the exported ray marcher gets the same two-level skip as the app.
  const brickOcc = new Uint32Array(16);
  world.forEach((x, y, z) => {
    const bi = (x >> 3) + ((y >> 3) << 3) + ((z >> 3) << 6);
    brickOcc[bi >> 5]! |= 1 << (bi & 31);
  });

  const f = (v: number): string => {
    const s = v.toFixed(6).replace(/0+$/, "");
    return s.endsWith(".") ? `${s}0` : s;
  };

  const matCases = [...usedMats]
    .sort((a, b) => a - b)
    .map((m) => {
      const e = palette[m]!;
      return `    case ${m}: return vec4(${f(e.r)}, ${f(e.g)}, ${f(e.b)}, ${f(e.emissive)});`;
    })
    .join("\n");

  const editsArray =
    edits.length === 0
      ? ""
      : `const uint EDITS[${edits.length}] = uint[${edits.length}](\n  ${edits
          .map((e) => `${e}u`)
          .join(", ")}\n);\n`;

  const lightsArray =
    shadowLights.length === 0
      ? ""
      : `const vec4 LIGHTS[${shadowLights.length}] = vec4[${shadowLights.length}](\n${shadowLights
          .map((l) => `  vec4(${f(l.x + 0.5)}, ${f(l.y + 0.5)}, ${f(l.z + 0.5)}, ${l.mat}.0)`)
          .join(",\n")}\n);\n`;

  const glsl = `// ---------------------------------------------------------------------------
// A room from VoxelDream — baked into a single self-contained shader.
//
// Nothing here is loaded: the room is re-generated by the same hash-driven
// function the editor used (roomVoxel + a PCG hash), and everything the
// player changed rides along as ${edits.length} packed uint edit${edits.length === 1 ? "" : "s"}
// (18-bit position | 8-bit material), found by binary search during the
// ray march. Two-level DDA (8^3 bricks, then voxels), direct lighting from
// the emissive voxels with shadow rays, voxel AO, ACES tonemap.
// The full path-traced version of this room lives in the editor; this
// export is its daylight-free, direct-light bake.
//
// Drop into a new shadertoy.com shader as the Image tab. No channels needed.
// Drag to orbit. Knobs: LIGHT_SCALE, AA, the sky() gradient.
// ---------------------------------------------------------------------------

#define WORLD 64
#define EDIT_COUNT ${edits.length}
#define LIGHT_COUNT ${shadowLights.length}
#define AA 2
const float LIGHT_SCALE = 3.0;
const uint SEED = ${seed >>> 0}u;

// --- PCG hash (Jarzynski & Olano, JCGT 2020) — twin of src/core/hash.ts ---
uint pcg(uint v) {
  uint state = v * 747796405u + 2891336453u;
  uint word = ((state >> ((state >> 28u) + 4u)) ^ state) * 277803737u;
  return (word >> 22u) ^ word;
}
uint hash3(uint x, uint y, uint z, uint s) { return pcg(x + pcg(y + pcg(z ^ s))); }

// --- The room generator — twin of src/dreams/room.ts::roomVoxel -----------
int roomVoxel(ivec3 p) {
  if (any(lessThan(p, ivec3(0))) || any(greaterThanEqual(p, ivec3(WORLD)))) return 0;
  if (p.y >= WORLD - 2) {
    uint jag = hash3(uint(p.x), 0u, 0u, SEED) & 3u;
    int halfWidth = (jag == 0u) ? 0 : 1;
    bool inCrack = p.x > 10 && p.x < 54 && p.z >= 31 - halfWidth && p.z <= 32 + halfWidth;
    return inCrack ? 0 : ${MAT.CEILING};
  }
  if (p.y <= 1) return ((((p.x >> 3) + (p.z >> 3)) & 1) == 0) ? ${MAT.FLOOR_A} : ${MAT.FLOOR_B};
  int wallDist = min(min(p.x, p.z), min(WORLD - 1 - p.x, WORLD - 1 - p.z));
  if (wallDist <= 1) return (p.y % 14 == 7) ? ${MAT.TRIM} : ${MAT.WALL};
  bool px = abs(p.x - 16) <= 1 || abs(p.x - 47) <= 1;
  bool pz = abs(p.z - 16) <= 1 || abs(p.z - 47) <= 1;
  if (px && pz) return ${MAT.PILLAR};
  if (p.y == 2 && hash3(uint(p.x), uint(p.y), uint(p.z), SEED) % 89u < 2u) return ${MAT.RUBBLE};
  return 0;
}

// --- What the player changed, as a sorted, binary-searched diff ------------
${editsArray}${lightsArray}
// Brick occupancy of the final world: 1 bit per 8^3 brick, so empty space
// is skipped eight voxels at a stride (same structure the editor traverses).
const uint BRICK_OCC[16] = uint[16](
  ${Array.from(brickOcc, (w) => `${w >>> 0}u`).join(", ")}
);

int voxelAt(ivec3 p) {
  if (any(lessThan(p, ivec3(0))) || any(greaterThanEqual(p, ivec3(WORLD)))) return 0;
#if EDIT_COUNT > 0
  int key = p.x | (p.y << 6) | (p.z << 12);
  int lo = 0, hi = EDIT_COUNT - 1;
  while (lo <= hi) {
    int mid = (lo + hi) >> 1;
    uint e = EDITS[mid];
    int k = int(e & 0x3ffffu);
    if (k == key) return int((e >> 18) & 0xffu);
    if (k < key) { lo = mid + 1; } else { hi = mid - 1; }
  }
#endif
  return roomVoxel(p);
}

bool brickSolid(ivec3 b) {
  uint i = uint(b.x) + uint(b.y) * 8u + uint(b.z) * 64u;
  return ((BRICK_OCC[i >> 5u] >> (i & 31u)) & 1u) == 1u;
}

// --- Palette (linear RGB + emissive intensity) ------------------------------
vec4 material(int m) {
  switch (m) {
${matCases}
    default: return vec4(0.5, 0.5, 0.5, 0.0);
  }
}

// --- Two-level DDA (Amanatides & Woo at brick scale, then voxel scale) ------
bool traceRay(vec3 ro, vec3 rd, float tMax, out ivec3 cell, out vec3 n, out float t) {
  rd.x = abs(rd.x) < 1e-6 ? (rd.x < 0.0 ? -1e-6 : 1e-6) : rd.x;
  rd.y = abs(rd.y) < 1e-6 ? (rd.y < 0.0 ? -1e-6 : 1e-6) : rd.y;
  rd.z = abs(rd.z) < 1e-6 ? (rd.z < 0.0 ? -1e-6 : 1e-6) : rd.z;
  vec3 inv = 1.0 / rd;

  vec3 tLo = (vec3(0.0) - ro) * inv;
  vec3 tHi = (vec3(float(WORLD)) - ro) * inv;
  vec3 tMin3 = min(tLo, tHi);
  vec3 tMax3 = max(tLo, tHi);
  float tNear = max(max(tMin3.x, tMin3.y), tMin3.z);
  float tFar = min(min(tMax3.x, tMax3.y), tMax3.z);
  if (tFar < max(tNear, 0.0)) return false;
  t = max(tNear + 1e-4, 0.0);
  if (t > tMax) return false;

  vec3 lastN = vec3(0.0);
  if (tNear > 0.0) {
    if (tNear == tMin3.x) lastN = vec3(-sign(rd.x), 0.0, 0.0);
    else if (tNear == tMin3.y) lastN = vec3(0.0, -sign(rd.y), 0.0);
    else lastN = vec3(0.0, 0.0, -sign(rd.z));
  }

  ivec3 stepI = ivec3(sign(rd));
  vec3 stepUp = max(sign(rd), vec3(0.0));

  vec3 p = ro + rd * t;
  ivec3 b = clamp(ivec3(floor(p / 8.0)), ivec3(0), ivec3(7));
  vec3 bNextT = (vec3(b * 8) + stepUp * 8.0 - ro) * inv;
  vec3 bDelta = abs(inv) * 8.0;

  for (int i = 0; i < 40; i++) {
    if (brickSolid(b)) {
      vec3 q = ro + rd * (t + 1e-4);
      ivec3 lo2 = b * 8;
      ivec3 v = clamp(ivec3(floor(q)), lo2, lo2 + ivec3(7));
      vec3 vNextT = (vec3(v) + stepUp - ro) * inv;
      vec3 vDelta = abs(inv);
      vec3 nn = lastN;
      float vt = t;
      for (int j = 0; j < 32; j++) {
        if (voxelAt(v) != 0) {
          if (vt > tMax) return false;
          cell = v; n = nn; t = vt;
          return true;
        }
        if (vNextT.x <= vNextT.y && vNextT.x <= vNextT.z) {
          vt = vNextT.x; vNextT.x += vDelta.x; v.x += stepI.x; nn = vec3(-sign(rd.x), 0.0, 0.0);
        } else if (vNextT.y <= vNextT.z) {
          vt = vNextT.y; vNextT.y += vDelta.y; v.y += stepI.y; nn = vec3(0.0, -sign(rd.y), 0.0);
        } else {
          vt = vNextT.z; vNextT.z += vDelta.z; v.z += stepI.z; nn = vec3(0.0, 0.0, -sign(rd.z));
        }
        if (any(lessThan(v, lo2)) || any(greaterThan(v, lo2 + ivec3(7)))) break;
      }
    }
    if (bNextT.x <= bNextT.y && bNextT.x <= bNextT.z) {
      t = bNextT.x; bNextT.x += bDelta.x; b.x += stepI.x; lastN = vec3(-sign(rd.x), 0.0, 0.0);
    } else if (bNextT.y <= bNextT.z) {
      t = bNextT.y; bNextT.y += bDelta.y; b.y += stepI.y; lastN = vec3(0.0, -sign(rd.y), 0.0);
    } else {
      t = bNextT.z; bNextT.z += bDelta.z; b.z += stepI.z; lastN = vec3(0.0, 0.0, -sign(rd.z));
    }
    if (t > min(tFar, tMax)) return false;
    if (any(lessThan(b, ivec3(0))) || any(greaterThan(b, ivec3(7)))) return false;
  }
  return false;
}

// --- Lighting ----------------------------------------------------------------
vec3 sky(vec3 rd) {
  float up = clamp(rd.y * 0.5 + 0.5, 0.0, 1.0);
  return mix(vec3(0.010, 0.014, 0.028), vec3(0.055, 0.075, 0.13), up);
}

// Voxel AO: how walled-in is the empty cell this surface faces?
float voxelAO(ivec3 cell, vec3 n) {
  ivec3 open = cell + ivec3(n);
  float occ = 0.0;
  for (int dx = -1; dx <= 1; dx++)
  for (int dy = -1; dy <= 1; dy++)
  for (int dz = -1; dz <= 1; dz++) {
    if (dx == 0 && dy == 0 && dz == 0) continue;
    if (voxelAt(open + ivec3(dx, dy, dz)) != 0) occ += 1.0;
  }
  return 1.0 - 0.55 * occ / 26.0;
}

vec3 shade(vec3 ro, vec3 rd) {
  ivec3 cell; vec3 n; float t;
  if (!traceRay(ro, rd, 1e4, cell, n, t)) return sky(rd);
  vec4 m = material(voxelAt(cell));
  if (m.a > 0.0) return m.rgb * m.a; // emissive voxels glow
  vec3 hp = ro + rd * t;
  float ao = voxelAO(cell, n);
  vec3 col = m.rgb * 0.02 * ao * (n.y * 0.3 + 0.7); // ambient whisper
#if LIGHT_COUNT > 0
  for (int i = 0; i < LIGHT_COUNT; i++) {
    vec4 l = LIGHTS[i];
    vec4 lm = material(int(l.w));
    vec3 wi = l.xyz - hp;
    float d2 = max(dot(wi, wi), 0.75);
    float dist = sqrt(d2);
    wi /= max(dist, 1e-4);
    float ndotl = dot(n, wi);
    if (ndotl <= 0.0) continue;
    ivec3 scell; vec3 sn; float st;
    bool hitSomething = traceRay(hp + n * 1e-3, wi, dist + 1.0, scell, sn, st);
    if (hitSomething && scell != ivec3(floor(l.xyz))) continue; // occluded
    col += m.rgb / 3.14159265 * lm.rgb * lm.a * LIGHT_SCALE * ndotl / d2 * ao;
  }
#endif
  return col;
}

vec3 aces(vec3 x) {
  return clamp((x * (2.51 * x + 0.03)) / (x * (2.43 * x + 0.59) + 0.14), 0.0, 1.0);
}

void mainImage(out vec4 fragColor, in vec2 fragCoord) {
  // Orbit inside the room; drag to steer.
  float yaw = iTime * 0.1 + 0.8;
  float pitch = 0.12 + 0.2 * sin(iTime * 0.05);
  if (iMouse.z > 0.0 || iMouse.w > 0.0) {
    yaw = 6.2831853 * (iMouse.x / iResolution.x) + 0.8;
    pitch = 1.9 * (iMouse.y / iResolution.y - 0.5);
  }
  pitch = clamp(pitch, -0.95, 0.95); // keep the orbit clear of floor/ceiling/pillars
  vec3 target = vec3(32.0, 24.0, 32.0);
  float dist = 19.0;
  vec3 ro = target + dist * vec3(cos(pitch) * sin(yaw), sin(pitch), cos(pitch) * cos(yaw));
  vec3 fwd = normalize(target - ro);
  vec3 right = normalize(cross(fwd, vec3(0.0, 1.0, 0.0)));
  vec3 up = cross(right, fwd);
  float tanF = 0.5774; // ~60 degree fov

  vec3 col = vec3(0.0);
  for (int sx = 0; sx < AA; sx++)
  for (int sy = 0; sy < AA; sy++) {
    vec2 o = (vec2(float(sx), float(sy)) + 0.5) / float(AA) - 0.5;
    vec2 uv = (2.0 * (fragCoord + o) - iResolution.xy) / iResolution.y;
    vec3 rd = normalize(fwd + right * uv.x * tanF + up * uv.y * tanF);
    col += shade(ro, rd);
  }
  col /= float(AA * AA);

  col = aces(col * 1.35);
  vec2 q = fragCoord / iResolution.xy - 0.5;
  col *= 1.0 - 0.5 * dot(q, q);
  fragColor = vec4(pow(col, vec3(1.0 / 2.2)), 1.0);
}
`;

  return { glsl, warnings, editCount: edits.length, lightCount: lights.length };
}
